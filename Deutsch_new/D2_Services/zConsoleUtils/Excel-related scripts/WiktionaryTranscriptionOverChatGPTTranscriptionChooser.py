    def _validate_line_format_is_correct(self, input_lines):
        validation_failures = []

        for line in input_lines:
            line = line.strip()
            if line and '\t' not in line:
                validation_failures.append(line)

        return validation_failures

    # Метод выводит в консоль сообщения о каждых 10% обработанных строк
    def _print_progress(self, loop_counter, total_lines, last_progress):
        # Отчёт о прогрессе
        progress = (loop_counter + 1) / total_lines * 100  # Вычисление процента

        # Проверка на ближайший 10%-ный шаг
        current_progress = int(progress // 10) * 10  # Округляем вниз до ближайшего десятка

        if current_progress > last_progress:  # Проверяем, достигли ли мы нового порога
            timestamp = datetime.now().strftime("%H:%M:%S")  # Получение текущего времени
            print(f"{timestamp} - Processed: {current_progress:.0f}%")  # Вывод прогресса с временной меткой
            last_progress = current_progress  # Обновляем последний выведенный процент

        return last_progress


